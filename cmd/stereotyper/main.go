package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"log"
	"os"
	"path/filepath"

	"golang.org/x/tools/go/packages"
)

const (
	corePkgPath    = "github.com/BeamFoundry/rays/pkg/core"
	interfaceName  = "Stereotype"
	outputFileName = "zz_stereotype.go"
)

func main() {
	// packages.Load config:
	// We need Names, Files (to find directories), Types, and Imports for interface resolution.
	// By omitting packages.NeedTests, test packages and _test.go files are automatically excluded.
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedTypes | packages.NeedImports | packages.NeedDeps,
		Dir:  ".", // Run in the root of the project importing rays
	}

	// Load the target project's packages ("./...") and explicitly load the core package
	// to guarantee we can inspect the Stereotype interface definition.
	pkgs, err := packages.Load(cfg, corePkgPath, "./...")
	if err != nil {
		log.Fatalf("Failed to load packages: %v", err)
	}
	if packages.PrintErrors(pkgs) > 0 {
		log.Println("Warning: Some packages had loading errors, proceeding with available valid types.")
	}

	var stereotypeIface *types.Interface

	// 1. Locate the core.Stereotype interface definition
	for _, pkg := range pkgs {
		if pkg.PkgPath != corePkgPath {
			continue
		}
		obj := pkg.Types.Scope().Lookup(interfaceName)
		if obj == nil {
			log.Fatalf("Interface %s not found in %s", interfaceName, corePkgPath)
		}
		named, ok := obj.Type().(*types.Named)
		if !ok {
			log.Fatalf("%s is not a named type", interfaceName)
		}
		iface, ok := named.Underlying().(*types.Interface)
		if !ok {
			log.Fatalf("%s is not an interface", interfaceName)
		}
		stereotypeIface = iface
		break
	}

	if stereotypeIface == nil {
		log.Fatalf("Could not locate %s.%s. Make sure it is imported or available in the module.", corePkgPath, interfaceName)
	}

	// 2. Scan all local packages for implementing structs
	for _, pkg := range pkgs {
		// Skip generating a file inside the rays core package itself if ran locally
		if pkg.PkgPath == corePkgPath {
			continue
		}

		var implementingStructs []string
		scope := pkg.Types.Scope()

		for _, name := range scope.Names() {
			obj := scope.Lookup(name)

			typeName, ok := obj.(*types.TypeName)
			if !ok {
				continue
			}

			// Ensure we are working with a struct
			if _, isStruct := typeName.Type().Underlying().(*types.Struct); !isStruct {
				continue
			}

			// Skip generic types (type parameters) since `&MyStruct{}` would cause a syntax error
			// without concrete type arguments.
			named, ok := typeName.Type().(*types.Named)
			if ok && named.TypeParams() != nil && named.TypeParams().Len() > 0 {
				continue
			}

			// Check if a pointer to this struct implements the interface.
			// Note: If a struct implements an interface via a value receiver, the pointer's
			// method set still contains the method. Therefore, checking the pointer covers both cases.
			ptrType := types.NewPointer(typeName.Type())
			if types.Implements(ptrType, stereotypeIface) {
				implementingStructs = append(implementingStructs, name)
			}
		}

		// 3. Generate zz_stereotype.go if matches were found
		if len(implementingStructs) > 0 {
			generateFile(pkg, implementingStructs)
		}
	}
}

func generateFile(pkg *packages.Package, structs []string) {
	if len(pkg.GoFiles) == 0 {
		return
	}

	// Determine the local filesystem directory for the current package
	pkgDir := filepath.Dir(pkg.GoFiles[0])
	outPath := filepath.Join(pkgDir, outputFileName)

	var buf bytes.Buffer

	buf.WriteString("// Code generated by stereotyper; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg.Name)

	// We use an aliased import `_rays_core` to prevent shadowing in case
	// the target package has a struct or variable coincidentally named `core`.
	fmt.Fprintf(&buf, "import _rays_core %q\n\n", corePkgPath)

	for _, s := range structs {
		fmt.Fprintf(&buf, "var _, _ = any(&%s{}).(_rays_core.%s)\n", s, interfaceName)
	}

	// Format the source code cleanly
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Printf("Failed to gofmt generated source for %s: %v", outPath, err)
		formatted = buf.Bytes()
	}

	if err := os.WriteFile(outPath, formatted, 0o600); err != nil {
		log.Printf("Failed to write %s: %v", outPath, err)
	}
}
